"""Full-dataset agreement rates by role and by lexical domain (CoT models).

Run with: .venv/bin/python scripts/final2_role_domain_alignment.py
Outputs tables/final2_role_alignment_heatmap.tex,
tables/final2_domain_alignment_heatmap.tex,
tables/final2_role_disagreement_delta.tex,
tables/final2_domain_disagreement_delta.tex,
outputs/report/final2_role_domain_alignment.csv and
outputs/report/final2_role_domain_delta.csv.

The heatmaps use all questions; the delta tables use only the questions where
Classical Logic and WCS disagree, which is where the two frameworks can be told apart.
"""

import csv
import statistics
from collections import Counter, defaultdict

from calc_classical_wcs_role_domain_alignment import (
    DOMAIN_ORDER,
    ROLE_ORDER,
    heatmap_cell,
    metric_by_group,
    summarize,
)
from final2_disagreement_table import COT_MODELS, ROOT, load_runs

TABLES_DIR = ROOT / "tables"
REPORT_PATH = ROOT / "outputs/report/final2_role_domain_alignment.csv"
DELTA_REPORT_PATH = ROOT / "outputs/report/final2_role_domain_delta.csv"
MAIN_TABLE_CSV = ROOT / "outputs/report/final2_per_sample.csv"
LOG_DIR = ROOT / "outputs/final"
MODEL_LABELS = {
    "Mistral-7B": "Mistral-7B",
    "Llama-3.1-8B": "Llama-8B",
    "OLMo-2-13B": "OLMo-13B",
    "DeepSeek-R1-Distill-Llama-8B": "DeepSeek-Llama-8B",
    "DeepSeek-R1-Distill-Qwen-14B": "DeepSeek-Qwen-14B",
    "Mistral-Small-24B": "Mistral-24B",
    "DeepSeek-R1-Distill-Qwen-32B": "DeepSeek-Qwen-32B",
}
FRAMEWORKS = (("classical", "Classical Logic", "green"), ("wcs", "WCS", "blue"))
GROUPS = (("role", ROLE_ORDER), ("domain", DOMAIN_ORDER))
DELTA_COLOUR_LIMIT = 50.0
DELTA_DARKEST_SHADE = 0.7


def supervisor_log_gap(path, run_stats):
    """Largest gap between our per-role accuracies and the supervisors' evaluation log."""
    log_name = path.name.replace("_predictions_", "_").replace(".jsonl", "_outputs_log.csv")
    with (LOG_DIR / log_name).open(encoding="utf-8") as source:
        rows = {row["role"]: row for row in csv.DictReader(source)}
    return max(
        abs(summarize(run_stats[framework]["role"][role]) / 100 - float(rows[role][f"acc_{framework}"]))
        for framework, _, _ in FRAMEWORKS for role in ROLE_ORDER
    )


def disagreement_delta(gold_rows, predictions_by_id):
    """WCS-minus-Classical match-rate difference per role and per domain for one run.

    Returns ({group: {value: delta in percentage points}}, {group: {value: number of questions}}).
    """
    counts = {group: defaultdict(Counter) for group, _ in GROUPS}
    for item in gold_rows:
        for code, conclusion in item["conclusions"].items():
            classical, wcs = conclusion["classical"], conclusion["wcs"]
            if classical == wcs:
                continue
            prediction = predictions_by_id[item["id"]]["conclusions"][code]["pred_index"]
            for group, _ in GROUPS:
                bucket = counts[group][item[group]]
                bucket["n"] += 1
                bucket["classical"] += prediction == classical
                bucket["wcs"] += prediction == wcs
    deltas = {
        group: {key: 100.0 * (b["wcs"] - b["classical"]) / b["n"] for key, b in by_key.items()}
        for group, by_key in counts.items()
    }
    sizes = {group: {key: b["n"] for key, b in by_key.items()} for group, by_key in counts.items()}
    return deltas, sizes


def delta_cell(mean, sd):
    """Shade a delta cell green (Classical-leaning) or blue (WCS-leaning).

    Uses the end colours and neutral midpoint of the by-form figure. The darkest shade is
    reached at +/-50 points, because per-role and per-domain values are smaller, and it is
    kept light enough for every number to stay in black.
    """
    neutral, classical, wcs = (242, 241, 237), (60, 120, 75), (60, 88, 150)
    target = wcs if mean > 0 else classical
    fraction = DELTA_DARKEST_SHADE * min(1.0, abs(mean) / DELTA_COLOUR_LIMIT)
    rgb = tuple(round(n + (t - n) * fraction) for n, t in zip(neutral, target))
    colour = "".join(f"{channel:02X}" for channel in rgb)
    return f"\\cellcolor[HTML]{{{colour}}}{mean:+.2f} $\\pm$ {sd:.2f}"


def write_delta_table(path, deltas, group, columns, caption, label):
    lines = [
        "% Generated by scripts/final2_role_domain_alignment.py",
        "% Requires \\usepackage[table]{xcolor} and \\usepackage{booktabs}",
        r"\begin{table}[H]",
        r"\centering",
        r"\caption{" + caption + "}",
        r"\label{" + label + "}",
        r"\begin{tabular}{l" + "r" * len(columns) + "}",
        r"\toprule",
        " & ".join(["Model", *(column.title() + r" $(\Delta)$" for column in columns)]) + r" \\",
        r"\midrule",
    ]
    for model, label_text in MODEL_LABELS.items():
        cells = [
            delta_cell(statistics.fmean(deltas[model][group][column]), statistics.stdev(deltas[model][group][column]))
            for column in columns
        ]
        lines.append(" & ".join([label_text, *cells]) + r" \\")
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_heatmap(path, stats, group, columns, caption, label):
    lines = [
        "% Generated by scripts/final2_role_domain_alignment.py",
        r"\begin{figure}[H]",
        r"\centering",
        r"\caption{" + caption + "}",
        r"\label{" + label + "}",
        r"\small",
    ]
    for index, (framework, title, color) in enumerate(FRAMEWORKS):
        if index:
            lines.append(r"\vspace{1.0em}")
        lines.extend([
            r"\begin{tabular}{lcccc}",
            r"\multicolumn{5}{c}{\textbf{" + title + r"}} \\",
            r"\toprule",
            " & ".join(["Model", *(column.title() for column in columns)]) + r" \\",
            r"\midrule",
        ])
        for model, label_text in MODEL_LABELS.items():
            cells = [heatmap_cell(stats[model][group][framework][column], color) for column in columns]
            lines.append(" & ".join([label_text, *cells]) + r" \\")
        lines.extend([r"\bottomrule", r"\end{tabular}"])
    lines.append(r"\end{figure}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    gold, runs_by_model = load_runs(models=COT_MODELS)
    gold_rows = list(gold.values())
    questions = {
        group: Counter(row[group] for row in gold_rows for _ in row["conclusions"])
        for group, _ in GROUPS
    }
    if any(count != 8192 for counts in questions.values() for count in counts.values()):
        raise ValueError(f"Expected 8192 questions per role and per domain: {questions}")

    with MAIN_TABLE_CSV.open(encoding="utf-8") as source:
        main_rows = list(csv.DictReader(source))

    stats = {}
    deltas = {}
    largest_log_gap = 0.0
    for model in MODEL_LABELS:
        deltas[model] = {group: {key: [] for key in keys} for group, keys in GROUPS}
        main_deltas = [float(row["delta"]) for row in main_rows if row["model"] == model]
        pooled = {group: {framework: {key: [] for key in keys} for framework, _, _ in FRAMEWORKS} for group, keys in GROUPS}
        for (path, predictions_by_id), main_delta in zip(runs_by_model[model], main_deltas, strict=True):
            run_delta, sizes = disagreement_delta(gold_rows, predictions_by_id)
            if any(size != 1280 for by_key in sizes.values() for size in by_key.values()):
                raise ValueError(f"Expected 1280 disagreement questions per role and per domain: {sizes}")
            # With no role, this is exactly the difference reported in the main table.
            if abs(run_delta["role"]["none"] - main_delta) > 1e-9:
                raise ValueError(f"{path.name}: neutral-role delta disagrees with the main table")
            for group, keys in GROUPS:
                for key in keys:
                    deltas[model][group][key].append(run_delta[group][key])
            run_stats = {
                framework: metric_by_group(gold_rows, predictions_by_id, framework)
                for framework, _, _ in FRAMEWORKS
            }
            largest_log_gap = max(largest_log_gap, supervisor_log_gap(path, run_stats))
            for group, keys in GROUPS:
                for framework, _, _ in FRAMEWORKS:
                    for key in keys:
                        pooled[group][framework][key].extend(run_stats[framework][group][key])
        stats[model] = {
            group: {framework: {key: summarize(values) for key, values in by_key.items()} for framework, by_key in frameworks.items()}
            for group, frameworks in pooled.items()
        }
    if largest_log_gap > 0.00051:
        raise ValueError(f"Per-role accuracy differs from the supervisors' logs by {largest_log_gap:.5f}")

    note = (
        "Each cell is the share of all 8,192 questions in that condition whose response matches the framework's gold "
        "label, averaged over five sampling runs; unparsed responses count as mismatches. Darker cells indicate higher agreement."
    )
    role_path = TABLES_DIR / "final2_role_alignment_heatmap.tex"
    write_heatmap(
        role_path, stats, "role", ROLE_ORDER,
        r"Agreement rates (\%) by role condition for the CoT models on the full all-forms dataset under Classical Logic and WCS. " + note,
        "fig:role-heatmap-final2",
    )
    domain_path = TABLES_DIR / "final2_domain_alignment_heatmap.tex"
    write_heatmap(
        domain_path, stats, "domain", DOMAIN_ORDER,
        r"Agreement rates (\%) by lexical domain for the CoT models on the full all-forms dataset under Classical Logic and WCS, pooled across the four role conditions. " + note,
        "fig:domain-heatmap-final2",
    )

    delta_note = (
        "Each cell uses the 1,280 disagreement questions in that condition and reports the mean $\\pm$ sample standard "
        "deviation across five sampling runs. Positive values indicate stronger WCS alignment, negative values stronger "
        "Classical alignment. Cells are shaded green for Classical-leaning and blue for WCS-leaning values, with the darkest "
        "shade at $\\pm$50 percentage points."
    )
    role_delta_path = TABLES_DIR / "final2_role_disagreement_delta.tex"
    write_delta_table(
        role_delta_path, deltas, "role", ROLE_ORDER,
        r"WCS-minus-Classical match-rate difference ($\Delta$, percentage points) by role condition on the questions where "
        "Classical Logic and WCS assign different gold labels, for the CoT models on the full all-forms dataset. "
        + delta_note + " The None column equals $\\Delta$ in the main disagreement table.",
        "tab:role-disagreement-delta-final2",
    )
    domain_delta_path = TABLES_DIR / "final2_domain_disagreement_delta.tex"
    write_delta_table(
        domain_delta_path, deltas, "domain", DOMAIN_ORDER,
        r"WCS-minus-Classical match-rate difference ($\Delta$, percentage points) by lexical domain on the questions where "
        "Classical Logic and WCS assign different gold labels, for the CoT models on the full all-forms dataset, pooled "
        "across the four role conditions. " + delta_note,
        "tab:domain-disagreement-delta-final2",
    )
    delta_rows = [
        {
            "model": model, "group": group, "value": key, "questions": 1280, "runs": len(deltas[model][group][key]),
            "delta_pp_mean": round(statistics.fmean(deltas[model][group][key]), 4),
            "delta_pp_sd": round(statistics.stdev(deltas[model][group][key]), 4),
        }
        for model in MODEL_LABELS for group, keys in GROUPS for key in keys
    ]
    with DELTA_REPORT_PATH.open("w", newline="", encoding="utf-8") as target:
        writer = csv.DictWriter(target, fieldnames=list(delta_rows[0]))
        writer.writeheader()
        writer.writerows(delta_rows)

    report_rows = [
        {
            "model": model, "group": group, "value": key,
            "classical_agreement_pct": round(stats[model][group]["classical"][key], 4),
            "wcs_agreement_pct": round(stats[model][group]["wcs"][key], 4),
        }
        for model in MODEL_LABELS for group, keys in GROUPS for key in keys
    ]
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with REPORT_PATH.open("w", newline="", encoding="utf-8") as target:
        writer = csv.DictWriter(target, fieldnames=list(report_rows[0]))
        writer.writeheader()
        writer.writerows(report_rows)

    for model, label_text in MODEL_LABELS.items():
        roles = stats[model]["role"]
        print(
            f"{label_text}: Classical by role "
            + ", ".join(f"{role} {roles['classical'][role]:.2f}" for role in ROLE_ORDER)
            + " | WCS " + ", ".join(f"{role} {roles['wcs'][role]:.2f}" for role in ROLE_ORDER)
        )
    print(f"Per-role accuracies match the supervisors' logs within rounding (largest gap {largest_log_gap:.5f}).")
    print("Neutral-role delta equals the main table for every run.")
    print(f"Wrote {role_path}")
    print(f"Wrote {domain_path}")
    print(f"Wrote {role_delta_path}")
    print(f"Wrote {domain_delta_path}")
    print(f"Wrote {DELTA_REPORT_PATH}")
    print(f"Wrote {REPORT_PATH}")


if __name__ == "__main__":
    main()
