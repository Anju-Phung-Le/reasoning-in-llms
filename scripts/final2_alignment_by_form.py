"""Full-dataset alignment by syllogistic form and by conclusion type (CoT models).

Neutral role only, so the figures add up to the main disagreement table.

Run with: .venv/bin/python scripts/final2_alignment_by_form.py
Outputs tables/final2_alignment_by_syllogistic_form.tex (figure),
tables/final2_alignment_by_syllogistic_form_heatmap.pdf,
tables/final2_alignment_by_syllogistic_form_appendix.tex and
tables/final2_alignment_by_conclusion_type.tex.
"""

import csv
from collections import Counter, defaultdict

from analyse_alignment_by_syllogistic_form import (
    CONCLUSION_TYPES,
    OUTCOMES,
    classify_prediction,
    rate,
    rate_delta,
    write_form_heatmap,
)
from final2_disagreement_table import COT_MODELS, DISPLAY_NAMES, ROOT, load_runs

TABLES_DIR = ROOT / "tables"
MAIN_TABLE_CSV = ROOT / "outputs/report/final2_per_sample.csv"
HEATMAP_NAME = "final2_alignment_by_syllogistic_form_heatmap.pdf"
# Same model names and order as the thesis tables.
MODEL_LABELS = {model: DISPLAY_NAMES[model] for model in COT_MODELS}
# The long names are broken over two lines so the heatmap column labels do not overlap.
FIGURE_LABELS = {model: label.replace("DeepSeek-", "DeepSeek-\n") for model, label in MODEL_LABELS.items()}
ROLE = "none"


def disagreement_cases(gold):
    cases = {}
    for item in gold.values():
        if item["role"] != ROLE:
            continue
        for code, conclusion in item["conclusions"].items():
            if conclusion["classical"] == conclusion["wcs"]:
                continue
            cases[(item["id"], code)] = {
                "form": item["form"],
                "type": CONCLUSION_TYPES[0] if code[0] in "AE" else CONCLUSION_TYPES[1],
                "classical": conclusion["classical"],
                "wcs": conclusion["wcs"],
            }
    return cases


def analyze(runs, cases):
    stats = {"runs": len(runs), "by_form": defaultdict(Counter), "by_type": defaultdict(Counter), "all": Counter()}
    for _, predictions_by_id in runs:
        for (iid, code), case in cases.items():
            outcome = classify_prediction(predictions_by_id[iid]["conclusions"][code], case)
            stats["by_form"][case["form"]][outcome] += 1
            stats["by_type"][case["type"]][outcome] += 1
            stats["all"][outcome] += 1
    return stats


def check_against_main_table(stats):
    """Summed over forms, the difference must equal the main table's mean for each model."""
    with MAIN_TABLE_CSV.open(encoding="utf-8") as source:
        rows = list(csv.DictReader(source))
    for model, model_stats in stats.items():
        deltas = [float(row["delta"]) for row in rows if row["model"] == model]
        if abs(rate_delta(model_stats["all"]) - sum(deltas) / len(deltas)) > 1e-9:
            raise ValueError(f"{model}: overall difference disagrees with the main table")


def main():
    gold, runs_by_model = load_runs(models=COT_MODELS)
    cases = disagreement_cases(gold)
    if len(cases) != 1280:
        raise ValueError(f"Expected 1280 neutral-role disagreement prompts, found {len(cases)}")

    stats = {model: analyze(runs_by_model[model], cases) for model in MODEL_LABELS}
    check_against_main_table(stats)
    models = list(MODEL_LABELS)
    forms = sorted({case["form"] for case in cases.values()})
    prompts_by_form = Counter(case["form"] for case in cases.values())
    prompts_by_type = Counter(case["type"] for case in cases.values())
    n_runs = stats[models[0]]["runs"]
    responses = f"Each prompt has {n_runs} generated responses per model."

    lines = [
        "% Generated by scripts/final2_alignment_by_form.py",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\caption{Net WCS-versus-Classical alignment on the "
        f"{len(cases):,} neutral-role disagreement questions in the full all-forms dataset, by syllogistic form. The "
        f"{len(forms)} forms shown are those with disagreements among the 64 possible forms. Entries are "
        "percentage-point differences: WCS-only response rate minus Classical-only response rate.}",
        r"\label{tab:alignment-by-syllogistic-form-appendix-final2}",
        r"\begin{tabular}{lr" + "r" * len(models) + "}",
        r"\toprule",
        " & ".join(["Form", "$n$", *(MODEL_LABELS[model] for model in models)]) + r" \\",
        r"\midrule",
    ]
    for form in forms:
        cells = [f"{rate_delta(stats[model]['by_form'][form]):+.1f}" for model in models]
        lines.append(" & ".join([form, str(prompts_by_form[form]), *cells]) + r" \\")
    lines.extend([
        r"\bottomrule",
        r"\end{tabular}",
        r"\vspace{2pt}",
        r"\begin{minipage}{\linewidth}",
        r"\scriptsize $n$ is the number of unique neutral-role disagreement prompts in that form. "
        + responses + " The denominator for each difference includes WCS-only, Classical-only, neither, and invalid "
        "responses; positive values lean WCS, negative values lean Classical.",
        r"\end{minipage}",
        r"\end{table}",
    ])
    form_path = TABLES_DIR / "final2_alignment_by_syllogistic_form_appendix.tex"
    form_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    figure_path = TABLES_DIR / "final2_alignment_by_syllogistic_form.tex"
    write_form_heatmap(
        stats, cases, TABLES_DIR / HEATMAP_NAME, figure_path,
        model_order=models, model_labels=FIGURE_LABELS,
        graphic_path=f"tables/{HEATMAP_NAME}", label_suffix="-final2",
    )
    # The shared plotting helper writes a caption for the role-pooled analysis; replace it.
    figure_path.write_text(
        "\n".join([
            "% Generated by scripts/final2_alignment_by_form.py",
            r"\begin{figure}[htbp]",
            r"\centering",
            r"\includegraphics[width=\linewidth,height=0.94\textheight,keepaspectratio]{tables/" + HEATMAP_NAME + "}",
            r"\caption{WCS-only minus Classical-only response-rate difference by syllogistic form on the "
            f"{len(cases):,} neutral-role disagreement questions in the full all-forms dataset. Green indicates a more "
            "Classical-leaning difference; blue indicates a more WCS-leaning difference; pale colors indicate little "
            "relative preference. Each row gives the number of unique neutral-role disagreement prompts in that form; "
            f"each prompt has {n_runs} generated responses per model. The shared color scale runs from $-100$ to $+100$ "
            "percentage points and is centered at zero.}",
            r"\label{tab:alignment-by-syllogistic-form-final2}",
            r"\end{figure}",
        ]) + "\n",
        encoding="utf-8",
    )

    lines = [
        "% Generated by scripts/final2_alignment_by_form.py",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\caption{Model responses on the "
        f"{len(cases):,} neutral-role Classical/WCS disagreement questions in the full all-forms dataset, split by "
        "conclusion type.}",
        r"\label{tab:alignment-by-conclusion-type-final2}",
        r"\begin{tabular}{llrrrrrr}",
        r"\toprule",
        r"Model & Type & $n$ & \shortstack{Classical\\only} & \shortstack{WCS\\only} & Neither & Invalid & $\Delta_{W-C}$ \\",
        r"\midrule",
    ]
    for model in models:
        for conclusion_type in CONCLUSION_TYPES:
            counts = stats[model]["by_type"][conclusion_type]
            cells = [
                MODEL_LABELS[model], conclusion_type, str(prompts_by_type[conclusion_type]),
                *(f"{rate(counts, outcome):.1f}\\%" for outcome in OUTCOMES),
                f"{rate_delta(counts):+.1f} pp",
            ]
            lines.append(" & ".join(cells) + r" \\")
            print(f"{MODEL_LABELS[model]} / {conclusion_type}: delta {rate_delta(counts):+.1f} pp")
    lines.extend([
        r"\bottomrule",
        r"\end{tabular}",
        r"\vspace{2pt}",
        r"\begin{minipage}{\linewidth}",
        r"\scriptsize Universal conclusions begin with A or E; particular conclusions begin with I or O. $n$ counts "
        f"unique neutral-role disagreement prompts, each evaluated with {n_runs} generations. "
        r"Percentages use all generated responses, including invalid outputs; $\Delta_{W-C}$ is WCS-only minus "
        "Classical-only in percentage points.",
        r"\end{minipage}",
        r"\end{table}",
    ])
    type_path = TABLES_DIR / "final2_alignment_by_conclusion_type.tex"
    type_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"Disagreement prompts: {len(cases)} across {len(forms)} forms; by type {dict(prompts_by_type)}")
    print("Summed over forms, every model reproduces its main-table difference.")
    print(f"Wrote {form_path}")
    print(f"Wrote {figure_path} and {TABLES_DIR / HEATMAP_NAME}")
    print(f"Wrote {type_path}")


if __name__ == "__main__":
    main()
