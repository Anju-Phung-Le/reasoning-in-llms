"""Full-dataset alignment decomposition and Neither/contradiction tables.

Run with: .venv/bin/python scripts/final2_neither_alignment.py
Outputs tables/final2_alignment_decomposition.tex,
tables/final2_neither_contradictions.tex and
outputs/report/final2_neither_alignment.csv.
"""

import csv

from analyze_neither_alignment import (
    DECOMPOSITIONS,
    aggregate_metric,
    analyze_run,
    category_for,
    denominator_counts,
    metric_values,
)
from final2_disagreement_table import ROOT, load_runs

TABLES_DIR = ROOT / "tables"
REPORT_PATH = ROOT / "outputs/report/final2_neither_alignment.csv"
MAIN_TABLE_CSV = ROOT / "outputs/report/final2_per_sample.csv"
SHORT_NAMES = {
    "DeepSeek-R1-Distill-Llama-8B": "DeepSeek-Llama-8B",
    "DeepSeek-R1-Distill-Qwen-14B": "DeepSeek-Qwen-14B",
    "DeepSeek-R1-Distill-Qwen-32B": "DeepSeek-Qwen-32B",
}
REPORT_METRICS = (
    "classical_only_pct", "wcs_only_pct", "neither_pct", "invalid_pct", "delta_pp",
    *(f"{name}_pct_all69" for name in DECOMPOSITIONS),
    *(f"{name}_conditional_pct" for name in DECOMPOSITIONS),
    "contradicts_classical_pct_all69", "contradicts_wcs_pct_all69",
    "contradicts_classical_conditional_pct", "contradicts_wcs_conditional_pct",
    "contradicts_classical_pct_neither", "contradicts_wcs_pct_neither",
)


def disagreement_targets(gold):
    targets = {}
    for item in gold.values():
        if item["role"] != "none":
            continue
        for code, conclusion in item["conclusions"].items():
            classical, wcs = conclusion["classical"], conclusion["wcs"]
            if classical != wcs:
                targets[(item["id"], code)] = {
                    "classical": classical, "wcs": wcs,
                    "category": category_for(classical, wcs),
                    "form": item["form"], "code": code,
                }
    return targets


def question_predictions(predictions_by_id, targets):
    return {key: predictions_by_id[key[0]]["conclusions"][key[1]] for key in targets}


def check_against_main_table(model_results, targets, denominators):
    """The outcome rates here must equal the per-sample rows behind the main table."""
    with MAIN_TABLE_CSV.open(encoding="utf-8") as source:
        rows = list(csv.DictReader(source))
    pairs = (
        ("classical_only_pct", "classical_match_pct"), ("wcs_only_pct", "wcs_match_pct"),
        ("neither_pct", "neither_pct"), ("invalid_pct", "unparsed_pct"),
    )
    for model, runs in model_results.items():
        expected = [row for row in rows if row["model"] == model]
        if len(expected) != len(runs):
            raise ValueError(f"{model}: {len(runs)} runs here, {len(expected)} in the main table")
        for run, row in zip(runs, expected):
            values = metric_values(run, targets, denominators)
            for here, there in pairs:
                if abs(values[here] - float(row[there])) > 1e-9:
                    raise ValueError(f"{model}: {here} disagrees with the main table")
            matched = run["decomposition"]
            if matched["classical_cd"] + matched["classical_definite"] != run["outcomes"]["classical_only"]:
                raise ValueError(f"{model}: Classical decomposition does not sum")
            if matched["wcs_cd"] + matched["wcs_definite"] != run["outcomes"]["wcs_only"]:
                raise ValueError(f"{model}: WCS decomposition does not sum")


def rate_cell(runs, targets, denominators, metric):
    """Mean (and SD over runs) without a unit; the column header carries the percent sign."""
    mean, sd = aggregate_metric([metric_values(run, targets, denominators) for run in runs], metric)
    return f"{mean:.2f}" if len(runs) == 1 else f"{mean:.2f} $\\pm$ {sd:.2f}"


def write_table(path, caption, label, header, metrics, footnote, model_results, targets, denominators):
    lines = [
        "% Generated by scripts/final2_neither_alignment.py",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{4pt}",
        r"\caption{" + caption + "}",
        r"\label{" + label + "}",
        r"\begin{tabular}{l" + "r" * len(metrics) + "}",
        r"\toprule",
        header + r" \\",
        r"\midrule",
    ]
    for model, runs in model_results.items():
        cells = [rate_cell(runs, targets, denominators, metric) for metric in metrics]
        lines.append(" & ".join([SHORT_NAMES.get(model, model), *cells]) + r" \\")
    lines.extend([
        r"\bottomrule",
        r"\end{tabular}",
        r"\vspace{2pt}",
        r"\begin{minipage}{\linewidth}",
        r"\scriptsize " + footnote,
        r"\end{minipage}",
        r"\end{table}",
    ])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    gold, runs_by_model = load_runs()
    targets = disagreement_targets(gold)
    denominators = denominator_counts(targets)
    total = len(targets)
    if total != 1280:
        raise ValueError(f"Expected 1280 neutral disagreements, found {total}")

    model_results = {
        model: [analyze_run(targets, question_predictions(predictions, targets)) for _, predictions in runs]
        for model, runs in runs_by_model.items()
    }
    check_against_main_table(model_results, targets, denominators)

    n_classical = denominators["classical_definite"]
    n_wcs = denominators["wcs_definite"]
    runs_note = (
        r"CoT entries are mean $\pm$ sample standard deviation over five sampling runs; "
        "FLAN-T5 entries are deterministic."
    )
    write_table(
        TABLES_DIR / "final2_alignment_decomposition.tex",
        f"Decomposition of Classical and WCS alignment on the {total:,} neutral-role disagreement questions "
        f"in the full all-forms dataset. Entries are percentages of all {total:,} questions. {runs_note}",
        "tab:alignment-decomposition-final2",
        r"Model & Classical CD (\%) & Classical Yes/No (\%) & WCS CD (\%) & WCS Yes/No (\%)",
        [f"{name}_pct_all69" for name in DECOMPOSITIONS],
        "CD means Cannot Determine. Each column counts responses that match that framework's gold label, split by "
        f"whether the gold label is CD or a definite Yes/No, divided by {total:,}. Classical CD plus Classical Yes/No "
        "equals the Classical match rate in the main table, and likewise for WCS. These are response-alignment rates, "
        "not evidence that a model internally implements either semantics.",
        model_results, targets, denominators,
    )
    write_table(
        TABLES_DIR / "final2_neither_contradictions.tex",
        "Neither response rates and conditional direct-contradiction rates on the neutral-role disagreement "
        "questions in the full all-forms dataset.",
        "tab:neither-direct-contradictions-final2",
        f"Model & Neither / {total} (\\%) & Classical definite / {n_classical} (\\%) & WCS definite / {n_wcs} (\\%)",
        ["neither_pct", "contradicts_classical_conditional_pct", "contradicts_wcs_conditional_pct"],
        f"Neither rate uses all {total:,} questions. The Classical and WCS columns are conditional rates: direct "
        "contradictions divided by the questions where that framework gives a definite Yes/No label "
        f"($n={n_classical}$ for Classical; $n={n_wcs}$ for WCS). A direct contradiction is the opposite definite "
        f"answer; CD is not a direct contradiction. {runs_note}",
        model_results, targets, denominators,
    )

    report_rows = []
    for model, runs in model_results.items():
        values = [metric_values(run, targets, denominators) for run in runs]
        row = {
            "model": model, "runs": len(runs), "questions": total,
            "classical_definite_questions": n_classical, "wcs_definite_questions": n_wcs,
        }
        for metric in REPORT_METRICS:
            mean, sd = aggregate_metric(values, metric)
            name = metric.replace("_pct_all69", "_pct_of_all")
            row[f"{name}_mean"] = "" if mean is None else round(mean, 4)
            row[f"{name}_sd"] = "" if sd is None else round(sd, 4)
        report_rows.append(row)
        print(
            f"{model}: neither {row['neither_pct_mean']:.2f}%, "
            f"contradicts Classical {row['contradicts_classical_conditional_pct_mean']:.2f}% of {n_classical}, "
            f"contradicts WCS {row['contradicts_wcs_conditional_pct_mean']:.2f}% of {n_wcs}"
        )
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with REPORT_PATH.open("w", newline="", encoding="utf-8") as target:
        writer = csv.DictWriter(target, fieldnames=list(report_rows[0]))
        writer.writeheader()
        writer.writerows(report_rows)

    print(f"Validated {sum(len(runs) for runs in model_results.values())} runs against the main table.")
    print(f"Wrote {TABLES_DIR / 'final2_alignment_decomposition.tex'}")
    print(f"Wrote {TABLES_DIR / 'final2_neither_contradictions.tex'}")
    print(f"Wrote {REPORT_PATH}")


if __name__ == "__main__":
    main()
