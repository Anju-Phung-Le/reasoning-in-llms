"""Full-dataset response-frequency baseline for Classical/WCS alignment.

Run with: .venv/bin/python scripts/final2_response_bias.py
Outputs tables/final2_response_bias_analysis.tex (figure),
tables/final2_response_bias_excess_delta.pdf,
tables/final2_response_bias_analysis_appendix.tex and
outputs/report/final2_response_bias.csv.
"""

import csv
import random

from analyze_response_bias import (
    INVALID,
    N_SHUFFLES,
    RANDOM_SEED,
    aggregate_runs,
    format_value,
    summarize_run,
    write_excess_delta_figure,
)
from final2_disagreement_table import DISPLAY_NAMES, ROOT, load_runs
from final2_neither_alignment import MAIN_TABLE_CSV, disagreement_targets, question_predictions

TABLES_DIR = ROOT / "tables"
REPORT_PATH = ROOT / "outputs/report/final2_response_bias.csv"
FIGURE_NAME = "final2_response_bias_excess_delta.pdf"
PANELS = (
    ("classical_pct", r"\textbf{Classical alignment}", r"Model & Observed (\%) & Shuffled base (\%) & Excess (pp)", r"\%"),
    ("wcs_pct", r"\textbf{WCS alignment}", r"Model & Observed (\%) & Shuffled base (\%) & Excess (pp)", r"\%"),
    ("delta_pp", r"\textbf{WCS-minus-Classical difference ($\Delta$)}", r"Model & Observed $\Delta$ & Shuffled expected $\Delta$ & Excess $\Delta$", " pp"),
)
ANSWERS = ((0, "yes"), (1, "no"), (2, "cd"), (INVALID, "invalid"))


def observed(metric):
    return lambda item: item["analysis"]["observed"][metric]


def baseline(metric):
    return lambda item: item["analysis"]["baseline"][f"{metric}_exact"]


def excess(metric):
    return lambda item: item["analysis"]["observed"][metric] - item["analysis"]["baseline"][f"{metric}_exact"]


def main():
    gold, runs_by_model = load_runs()
    targets = disagreement_targets(gold)
    total = len(targets)
    if total != 1280:
        raise ValueError(f"Expected 1280 neutral disagreements, found {total}")

    with MAIN_TABLE_CSV.open(encoding="utf-8") as source:
        main_rows = list(csv.DictReader(source))

    rng = random.Random(RANDOM_SEED)
    model_runs = {}
    for model, runs in runs_by_model.items():
        expected = [float(row["delta"]) for row in main_rows if row["model"] == model]
        model_runs[model] = []
        for (path, predictions_by_id), main_delta in zip(runs, expected, strict=True):
            analysis = summarize_run(targets, question_predictions(predictions_by_id, targets), rng)
            if abs(analysis["observed"]["delta_pp"] - main_delta) > 1e-9:
                raise ValueError(f"{path.name}: observed delta disagrees with the main table")
            analysis["observed"]["excess_delta_pp"] = excess("delta_pp")({"analysis": analysis})
            model_runs[model].append({"path": path, "analysis": analysis})
        print(f"{model}: {len(model_runs[model])} run(s) shuffled", flush=True)

    # Same model names and order as the thesis tables.
    display_runs = {DISPLAY_NAMES[model]: runs for model, runs in model_runs.items()}
    specs = [{"name": name, "short": name} for name in display_runs]
    write_excess_delta_figure(TABLES_DIR / FIGURE_NAME, display_runs, specs)
    (TABLES_DIR / "final2_response_bias_analysis.tex").write_text(
        "\n".join([
            "% Generated by scripts/final2_response_bias.py",
            r"\begin{figure}[htbp]",
            r"\centering",
            r"\includegraphics[width=0.95\linewidth]{tables/" + FIGURE_NAME + "}",
            r"\caption{Excess WCS-minus-Classical alignment on the "
            f"{total:,} neutral-role disagreement questions in the full all-forms dataset. "
            "The plotted difference is the observed WCS-minus-Classical match-rate difference minus its expected value "
            "under a shuffle preserving each model's Yes/No/CD/Invalid frequencies. Positive values indicate more WCS "
            "alignment than answer frequency alone predicts; negative values indicate more Classical alignment. "
            "Error bars show the sample standard deviation across five CoT sampling runs; FLAN-T5 outputs are deterministic.}",
            r"\label{fig:response-bias-delta-final2}",
            r"\end{figure}",
        ]) + "\n",
        encoding="utf-8",
    )

    lines = [
        "% Generated by scripts/final2_response_bias.py",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\caption{Observed alignment compared with a response-frequency baseline on the "
        f"{total:,} neutral-role disagreement questions in the full all-forms dataset. For each model run, predictions "
        f"were shuffled {N_SHUFFLES:,} times across the same {total:,} questions, preserving the model's "
        "Yes/No/CD/Invalid frequencies. Positive excess indicates alignment above that baseline.}",
        r"\label{tab:response-bias-alignment-final2}",
    ]
    for index, (metric, title, header, suffix) in enumerate(PANELS):
        if index:
            lines.append(r"\vspace{4pt}")
        lines.extend([title, r"\begin{tabular}{lrrr}", r"\toprule", header + r" \\", r"\midrule"])
        for model, runs in model_runs.items():
            cells = [DISPLAY_NAMES[model]]
            for getter, cell_suffix in ((observed(metric), suffix), (baseline(metric), suffix), (excess(metric), " pp")):
                mean, sd = aggregate_runs(runs, getter)
                cells.append(format_value(mean, sd, len(runs), cell_suffix))
            lines.append(" & ".join(cells) + r" \\")
        lines.extend([r"\bottomrule", r"\end{tabular}"])
    lines.extend([
        r"\vspace{2pt}",
        r"\begin{minipage}{\linewidth}",
        r"\scriptsize Base is the exact expected match rate under a uniform random permutation of the fixed answer "
        f"multiset; {N_SHUFFLES:,} actual shuffles estimate the corresponding null SD and check the expectation. "
        f"Excess = observed minus shuffled expectation. Percentages use all {total:,} questions. For CoT models, "
        r"$\pm$ is the sample SD across five sampling runs; FLAN-T5 outputs are deterministic. This baseline controls "
        "only answer frequencies, not question difficulty or dependencies among conclusions.",
        r"\end{minipage}",
        r"\end{table}",
    ])
    (TABLES_DIR / "final2_response_bias_analysis_appendix.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    report_rows = []
    for model, runs in model_runs.items():
        row = {"model": model, "runs": len(runs), "questions": total, "shuffles_per_run": N_SHUFFLES}
        for metric, *_ in PANELS:
            for name, getter in (("observed", observed(metric)), ("shuffled_expected", baseline(metric)), ("excess", excess(metric))):
                mean, sd = aggregate_runs(runs, getter)
                row[f"{name}_{metric}_mean"], row[f"{name}_{metric}_sd"] = round(mean, 4), round(sd, 4)
            mean, _ = aggregate_runs(runs, lambda item: item["analysis"]["baseline"][f"{metric}_null_sd"])
            row[f"shuffle_null_sd_{metric}_mean"] = round(mean, 4)
        for answer, name in ANSWERS:
            mean, sd = aggregate_runs(runs, lambda item: item["analysis"]["observed"]["answer_pct"][answer])
            row[f"answer_{name}_pct_mean"], row[f"answer_{name}_pct_sd"] = round(mean, 4), round(sd, 4)
        report_rows.append(row)
        print(
            f"{model}: observed delta {row['observed_delta_pp_mean']:+.2f}, "
            f"shuffled {row['shuffled_expected_delta_pp_mean']:+.2f}, excess {row['excess_delta_pp_mean']:+.2f} pp"
        )
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with REPORT_PATH.open("w", newline="", encoding="utf-8") as target:
        writer = csv.DictWriter(target, fieldnames=list(report_rows[0]))
        writer.writeheader()
        writer.writerows(report_rows)

    print(f"Shuffled each of {sum(len(runs) for runs in model_runs.values())} runs {N_SHUFFLES:,} times (seed {RANDOM_SEED}).")
    print(f"Wrote {TABLES_DIR / 'final2_response_bias_analysis.tex'} and {TABLES_DIR / FIGURE_NAME}")
    print(f"Wrote {TABLES_DIR / 'final2_response_bias_analysis_appendix.tex'}")
    print(f"Wrote {REPORT_PATH}")


if __name__ == "__main__":
    main()
