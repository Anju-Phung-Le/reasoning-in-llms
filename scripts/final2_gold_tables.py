"""Write the full-dataset gold-label tables.

Run with: .venv/bin/python scripts/final2_gold_tables.py
Outputs tables/final2_label_distribution_by_sample.tex and
tables/final2_classical_wcs_disagreement_heatmap.tex.
"""

from collections import Counter

from final2_disagreement_table import GOLD_PATH, ROOT, load_unique

TABLES_DIR = ROOT / "tables"
LABELS = {0: "Yes", 1: "No", 2: "CD"}
HEATMAP_LABELS = {0: "Yes", 1: "No", 2: "Cannot determine"}
FRAMEWORKS = (("Classical", "classical"), ("WCS", "wcs"))


def neutral_questions():
    """Return (form, code, classical, wcs) for every neutral-role question."""
    questions = []
    for item in load_unique(GOLD_PATH).values():
        if item["role"] != "none":
            continue
        for code, conclusion in item["conclusions"].items():
            questions.append((item["form"], code, conclusion["classical"], conclusion["wcs"]))
    return questions


def main():
    questions = neutral_questions()
    disagreements = [q for q in questions if q[2] != q[3]]
    distinct = {(form, code) for form, code, _, _ in disagreements}
    forms = {form for form, _ in distinct}
    if (len(questions), len(disagreements), len(distinct)) != (8192, 1280, 80):
        raise ValueError(
            f"Unexpected sample: {len(questions)} questions, "
            f"{len(disagreements)} disagreements, {len(distinct)} distinct pairs"
        )
    repeats = len(disagreements) // len(distinct)

    lines = [
        "% Generated by scripts/final2_gold_tables.py",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\small",
        r"\setlength{\tabcolsep}{3pt}",
        r"\caption{Gold-label distributions under Classical Logic and WCS for all neutral-role questions in the full all-forms dataset and for the neutral-role disagreement subset. Percentages use the sample size shown.}",
        r"\label{tab:label-distribution-by-sample-final2}",
        r"\begin{tabular}{llrrr}",
        r"\toprule",
        r"Sample & Framework & Yes & No & CD \\",
        r"\midrule",
    ]
    for label, sample in (("All-forms neutral", questions), ("Neutral disagreements", disagreements)):
        for index, (framework, _) in enumerate(FRAMEWORKS):
            counts = Counter(q[2 + index] for q in sample)
            cells = [
                f"{counts[key]} ({100.0 * counts[key] / len(sample):.1f}\\%)"
                for key in LABELS
            ]
            first = f"{label} ($n={len(sample)}$)" if index == 0 else ""
            lines.append(" & ".join([first, framework, *cells]) + r" \\")
            print(f"{label} / {framework}: " + ", ".join(f"{LABELS[k]}={counts[k]}" for k in LABELS))
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    distribution_path = TABLES_DIR / "final2_label_distribution_by_sample.tex"
    distribution_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    matrix = Counter((classical, wcs) for _, _, classical, wcs in disagreements)
    lines = [
        "% Generated by scripts/final2_gold_tables.py",
        "% Requires \\usepackage[table]{xcolor} and \\usepackage{booktabs}",
        r"\begin{table}[H]",
        r"\centering",
        r"\caption{Classical/WCS gold-label combinations on the "
        f"{len(disagreements):,} neutral-role conclusion questions in the full all-forms dataset where the frameworks disagree. "
        f"These are {len(distinct)} distinct form--conclusion pairs from {len(forms)} syllogistic forms, each realised with {repeats} lexical instantiations. "
        f"Counts and percentages use all {len(disagreements):,} questions." + "}",
        r"\label{tab:classical-wcs-disagreement-heatmap-final2}",
        r"\begin{tabular}{lrrr}",
        r"\toprule",
        r"Classical / WCS & Yes & No & Cannot determine \\",
        r"\midrule",
    ]
    for classical in HEATMAP_LABELS:
        cells = []
        for wcs in HEATMAP_LABELS:
            count = matrix[(classical, wcs)]
            share = 100.0 * count / len(disagreements)
            cells.append(f"\\cellcolor{{blue!{round(share)}}}{count} ({share:.1f}\\%)")
        lines.append(" & ".join([HEATMAP_LABELS[classical], *cells]) + r" \\")
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    heatmap_path = TABLES_DIR / "final2_classical_wcs_disagreement_heatmap.tex"
    heatmap_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"Disagreements: {len(disagreements)} = {len(distinct)} distinct pairs x {repeats}, from {len(forms)} forms")
    print("Nonzero cells:", {f"{HEATMAP_LABELS[c]}/{HEATMAP_LABELS[w]}": n for (c, w), n in sorted(matrix.items())})
    print(f"Wrote {distribution_path}")
    print(f"Wrote {heatmap_path}")


if __name__ == "__main__":
    main()
