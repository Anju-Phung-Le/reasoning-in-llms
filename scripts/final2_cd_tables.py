"""Full-dataset Cannot-Determine (CD) tables for the CoT models.

Run with: .venv/bin/python scripts/final2_cd_tables.py
Outputs tables/final2_cd_overall.tex, tables/final2_cd_per_framework.tex and
outputs/report/final2_cd_analysis.csv.
"""

import csv

from analyse_cd_precision_recall import mean_std, score_seed
from analyze_cd_per_framework import score_cd
from final2_disagreement_table import COT_MODELS, ROOT, load_runs

TABLES_DIR = ROOT / "tables"
REPORT_PATH = ROOT / "outputs/report/final2_cd_analysis.csv"
LOG_DIR = ROOT / "outputs/final"
BUCKETS = ("both", "only_cls", "only_wcs", "neither")
RUNS_NOTE = (
    r"Values are mean $\pm$ sample standard deviation across five sampling runs. "
    "Unparsed responses are kept in every denominator and count as non-CD responses."
)


def neutral_targets(gold):
    return {
        (item["id"], code): conclusion
        for item in gold.values() if item["role"] == "none"
        for code, conclusion in item["conclusions"].items()
    }


def supervisor_log_gaps(path, metrics, framework_metrics):
    """Gaps between our neutral-role CD figures and the supervisors' evaluation log.

    Returns (largest gap in overall CD rate and precision, largest gap in recall).
    The logs drop unparsed responses from the recall denominator; we keep them as
    non-CD responses, so only the first gap has to stay within the logs' rounding.
    """
    log_name = path.name.replace("_predictions_", "_").replace(".jsonl", "_outputs_log.csv")
    with (LOG_DIR / log_name).open(encoding="utf-8") as source:
        row = next(r for r in csv.DictReader(source) if r["role"] == "none")
    same_definition = {
        "c_usage": metrics["model_NVC_pct"] / 100,
        "precision_C_classical": framework_metrics["classical"]["precision"],
        "precision_C_wcs": framework_metrics["wcs"]["precision"],
    }
    recall = {
        "recall_C_classical": framework_metrics["classical"]["recall"],
        "recall_C_wcs": framework_metrics["wcs"]["recall"],
    }
    gap = max(abs(value - float(row[key])) for key, value in same_definition.items())
    if gap > 0.00051:
        raise ValueError(f"{path.name}: overall CD rate or precision differs from the supervisors' log by {gap:.5f}")
    return gap, max(abs(value - float(row[key])) for key, value in recall.items())


def fmt(values):
    mean, sd = mean_std(values)
    return f"{mean:.2f} $\\pm$ {sd:.2f}"


def main():
    gold, runs_by_model = load_runs(models=COT_MODELS)
    targets = neutral_targets(gold)
    if len(targets) != 8192:
        raise ValueError(f"Expected 8192 neutral-role questions, found {len(targets)}")

    results = {}
    largest_log_gap = largest_recall_gap = 0.0
    for model, runs in runs_by_model.items():
        results[model] = []
        for path, predictions_by_id in runs:
            metrics = score_seed(path, gold)
            predictions = {key: predictions_by_id[key[0]]["conclusions"][key[1]] for key in targets}
            framework_metrics = {
                framework: score_cd(targets, predictions, framework)
                for framework in ("classical", "wcs")
            }
            # Two separate implementations must agree on the framework-specific CD rate.
            for framework in ("classical", "wcs"):
                recall = 100 * framework_metrics[framework]["recall"]
                if abs(recall - metrics[f"nvc_rate_{framework}_cd_gold_pct"]) > 1e-9:
                    raise ValueError(f"{path.name}: {framework} CD rate differs between implementations")
            if metrics["n_overall"] != len(targets):
                raise ValueError(f"{path.name}: scored {metrics['n_overall']} questions")
            gap, recall_gap = supervisor_log_gaps(path, metrics, framework_metrics)
            largest_log_gap = max(largest_log_gap, gap)
            largest_recall_gap = max(largest_recall_gap, recall_gap)
            for framework in ("classical", "wcs"):
                for name in ("precision", "recall", "f1"):
                    metrics[f"{framework}_{name}_pct"] = 100 * framework_metrics[framework][name]
            results[model].append(metrics)

    first = next(iter(results.values()))[0]
    sizes = {bucket: first[f"n_{bucket}"] for bucket in BUCKETS}
    n_classical, n_wcs = first["n_classical_cd_gold"], first["n_wcs_cd_gold"]
    if sum(sizes.values()) != len(targets):
        raise ValueError(f"Gold-label categories do not cover all questions: {sizes}")

    lines = [
        "% Generated by scripts/final2_cd_tables.py",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\setlength{\tabcolsep}{3pt}",
        r"\caption{Overall use of the Cannot-Determine (CD) response on the "
        f"{len(targets):,} neutral-role questions in the full all-forms dataset. {RUNS_NOTE}" + "}",
        r"\label{tab:cd-overall-final2}",
        r"\begin{tabular}{lr}",
        r"\toprule",
        r"Model & Overall CD (\%) \\",
        r"\midrule",
    ]
    for model, runs in results.items():
        lines.append(f"{model} & {fmt([run['model_NVC_pct'] for run in runs])} \\\\")
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\vspace{2pt}", r"\end{table}"])
    overall_path = TABLES_DIR / "final2_cd_overall.tex"
    overall_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    lines = [
        "% Generated by scripts/final2_cd_tables.py",
        r"\begin{table}[H]",
        r"\centering",
        r"\setlength{\tabcolsep}{3pt}",
        r"\caption{Model \emph{Cannot determine} response rate (\%) by gold-label category on the "
        f"{len(targets):,} neutral-role questions in the full all-forms dataset. "
        "Both = both frameworks label CD; Classical only = only Classical labels CD; WCS only = only WCS labels CD; "
        f"Neither = neither labels CD. Category sizes are $n={sizes['both']}$, ${sizes['only_cls']}$, "
        f"${sizes['only_wcs']}$, and ${sizes['neither']}$, respectively. Panel B combines Both + Classical only "
        f"($n={n_classical}$) for Classical and Both + WCS only ($n={n_wcs}$) for WCS. {RUNS_NOTE}" + "}",
        r"\label{tab:cannot-determine-per-frameworks-final2}",
        r"\textbf{Panel A: CD response rate by gold-label category}\\",
        r"\par\vspace{4pt}",
        r"\begin{tabular}{lrrrr}",
        r"\toprule",
        r"Model & Both (\%) & Classical only (\%) & WCS only (\%) & Neither (\%) \\",
        r"\midrule",
    ]
    for model, runs in results.items():
        cells = [fmt([run[f"nvc_rate_{bucket}_pct"] for run in runs]) for bucket in BUCKETS]
        lines.append(" & ".join([model, *cells]) + r" \\")
    lines.extend([
        r"\bottomrule",
        r"\end{tabular}",
        r"\vspace{4pt}",
        "",
        r"\textbf{Panel B: Framework specific CD Recall}\\",
        r"\par\vspace{4pt}",
        r"\begin{tabular}{lrr}",
        r"\toprule",
        r"Model & Classical CD rate (\%) & WCS CD rate (\%) \\",
        r"\midrule",
    ])
    for model, runs in results.items():
        cells = [
            fmt([run["nvc_rate_classical_cd_gold_pct"] for run in runs]),
            fmt([run["nvc_rate_wcs_cd_gold_pct"] for run in runs]),
        ]
        lines.append(" & ".join([model, *cells]) + r" \\")
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    framework_path = TABLES_DIR / "final2_cd_per_framework.tex"
    framework_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    report_metrics = [
        "model_A_pct", "model_B_pct", "model_NVC_pct",
        *(f"nvc_rate_{bucket}_pct" for bucket in BUCKETS),
        *(f"{framework}_{name}_pct" for framework in ("classical", "wcs") for name in ("precision", "recall", "f1")),
    ]
    report_rows = []
    for model, runs in results.items():
        row = {"model": model, "runs": len(runs), "questions": len(targets)}
        for metric in report_metrics:
            mean, sd = mean_std([run[metric] for run in runs])
            row[f"{metric}_mean"], row[f"{metric}_sd"] = round(mean, 4), round(sd, 4)
        report_rows.append(row)
        print(
            f"{model}: overall CD {row['model_NVC_pct_mean']:.2f}%, "
            f"Classical recall {row['classical_recall_pct_mean']:.2f}%, WCS recall {row['wcs_recall_pct_mean']:.2f}%"
        )
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with REPORT_PATH.open("w", newline="", encoding="utf-8") as target:
        writer = csv.DictWriter(target, fieldnames=list(report_rows[0]))
        writer.writeheader()
        writer.writerows(report_rows)

    print(f"Category sizes: {sizes}; Classical CD gold {n_classical}, WCS CD gold {n_wcs}")
    print(f"Overall CD rate and precision match the supervisors' logs within rounding (largest gap {largest_log_gap:.5f}).")
    print(f"Recall differs from the logs by up to {largest_recall_gap:.5f}: the logs exclude unparsed responses, we count them as non-CD.")
    print(f"Wrote {overall_path}")
    print(f"Wrote {framework_path}")
    print(f"Wrote {REPORT_PATH}")


if __name__ == "__main__":
    main()
